//! dwmapi.dll loader-hijack proxy.
//!
//! Placed next to `steam.exe`, this DLL is loaded in preference to the
//! system `%WINDIR%\System32\dwmapi.dll` because the application directory
//! precedes the system directory in the default search order. The export
//! table (see `dwmapi.def`) forwards every named export and every
//! ordinal-only export to the real system DLL, so nothing else notices the
//! substitution.
//!
//! The only non-forwarding behaviour is in `DllMain`: after disabling
//! thread-attach notifications, and only when the host is `steam.exe`, load
//! `RustyTools.dll` so the hook layer's own init thread starts. Every
//! other host (rundll32, dwm.exe) gets a pass-through DLL with no side
//! effects.

#![allow(non_snake_case)]

// Generated by build.rs: one `#[link_section = ".drectve"]` static per
// named export in dwmapi.def. `.drectve` sections carry linker options;
// this is the object-file equivalent of the C++ `#pragma comment(linker,
// "/EXPORT:Name=DWMAPI.Name,@Ord")` block, and is the only form that does
// not normalise `DWMAPI` to the output DLL name and collapse the forwarder
// into a self-reference.
#[cfg(not(test))]
mod _dwmapi_exports {
    include!(concat!(env!("OUT_DIR"), "/dwmapi_exports_drectve.rs"));
}

#[cfg(not(windows))]
mod stub {}

#[cfg(windows)]
mod win {
    use std::ffi::c_void;
    use windows_sys::Win32::System::LibraryLoader::{
        DisableThreadLibraryCalls, GetModuleFileNameA, LoadLibraryA,
    };

    // Win32 DLL entry reasons. Values match the SDK headers (`minwindef.h`).
    const DLL_PROCESS_ATTACH: u32 = 1;
    const DLL_PROCESS_DETACH: u32 = 0;

    /// True only when the host process is `steam.exe`.
    fn is_steam_host() -> bool {
        let mut buf = [0u8; 260];
        let n = unsafe {
            GetModuleFileNameA(std::ptr::null_mut(), buf.as_mut_ptr(), buf.len() as u32)
        };
        if n == 0 {
            return false;
        }
        let path = &buf[..n as usize];
        // Take the final path component (last backslash onwards).
        let name_start = path
            .iter()
            .rposition(|&b| b == b'\\')
            .map(|i| i + 1)
            .unwrap_or(0);
        let name = &path[name_start..];
        name.eq_ignore_ascii_case(b"steam.exe")
    }

    /// Load `RustyTools.dll` from the current directory, but only when
    /// running inside `steam.exe`. `LoadLibraryA` is idempotent per process,
    /// so several hijack DLLs can call this without coordination — the
    /// second and later calls just bump the refcount.
    ///
    /// Returns `false` only when the load was attempted and failed; a
    /// non-Steam host returns `true` and is left untouched.
    fn rustytools_load() -> bool {
        if !is_steam_host() {
            return true;
        }
        let name = b"RustyTools.dll\0";
        !unsafe { LoadLibraryA(name.as_ptr()) }.is_null()
    }

    #[no_mangle]
    pub unsafe extern "system" fn DllMain(
        hmodule: *mut c_void,
        reason: u32,
        _reserved: *mut c_void,
    ) -> i32 {
        match reason {
            DLL_PROCESS_ATTACH => {
                DisableThreadLibraryCalls(hmodule);
                // A failed load of RustyTools.dll aborts our own load.
                // The host's dwmapi import then fails and the process does
                // not start, which is safer than silently running without
                // the hook layer it was configured to install.
                if !rustytools_load() {
                    return 0; // FALSE
                }
            }
            DLL_PROCESS_DETACH => {}
            _ => {}
        }
        1 // TRUE
    }
}
